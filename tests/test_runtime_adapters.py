def _response(
    status: int,
    value: Mapping[str, Any] | None = None,
    *,
    headers: Mapping[str, str] | None = None,
) -> HttpResponse:
    return HttpResponse(
        status_code=status,
        headers=headers or {},
        body=json.dumps(value or {}, separators=(",", ":")).encode("ascii"),
    )


class QueueTransport:
    def __init__(self, responses: list[HttpResponse]) -> None:
        self.responses = list(responses)
        self.calls: list[dict[str, Any]] = []
        self.lock = threading.Lock()

    def request(self, method, url, *, headers, body, timeout_seconds):
        with self.lock:
            self.calls.append(
                {
                    "method": method,
                    "url": url,
                    "headers": dict(headers),
                    "body": body,
                    "timeout_seconds": timeout_seconds,
                }
            )
            if not self.responses:
                raise AssertionError(f"Unexpected request: {method} {url}")
            return self.responses.pop(0)


def _metadata(run_id: str, digest: str) -> dict[str, str]:
    return {OWNER_KEY: OWNER_VALUE, RUN_KEY: run_id, DIGEST_KEY: digest}


def test_definition_and_source_hashes_are_deterministic(tmp_path: Path) -> None:
    definition = {"kind": "prompt", "tools": [], "model": "synthetic"}
    assert canonical_json_digest(definition) == canonical_json_digest(
        {"model": "synthetic", "tools": [], "kind": "prompt"}
    )
    source = tmp_path / "source"
    source.mkdir()
    (source / "main.py").write_bytes(b"print('healthy')\n")
    (source / "requirements.txt").write_bytes(b"example==1.0\n")
    first, first_digest = deterministic_zip(source)
    second, second_digest = deterministic_zip(source)
    assert first == second
    assert first_digest == second_digest
    assert first_digest == "sha256:c047775d84ad57a04b790b7c1b26208196e1a6bc76a4fe558cd0ad94351359c4"
    with zipfile.ZipFile(BytesIO(first)) as archive:
        assert all(info.create_system == 3 for info in archive.infolist())


def test_deployment_zip_ignores_the_same_generated_artifacts_as_catalog_hash(
    tmp_path: Path,
) -> None:
    source = tmp_path / "source"
    reviewed = source / "main.py"
    reviewed.parent.mkdir()
    reviewed.write_text("print('reviewed')\n", encoding="ascii")
    expected, expected_digest = deterministic_zip(source)

    for path in (
        source / "__pycache__" / "main.cpython-312.pyc",
        source / "build" / "generated.py",
        source / ".scratch.json",
        source / "transient.tmp",
    ):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(b"ignored generated bytes")

    observed, observed_digest = deterministic_zip(source)
    assert observed == expected
    assert observed_digest == expected_digest

    reviewed.write_text("print('changed')\n", encoding="ascii")
    assert deterministic_zip(source)[1] != expected_digest


