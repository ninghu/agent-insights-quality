def test_deployment_poll_preserves_transient_timeout_classification() -> None:
    definition = {"kind": "prompt", "model": "test", "tools": []}

    class CreateThenTimeoutTransport:
        def __init__(self) -> None:
            self.calls = 0

        def request(self, *_args, **kwargs):
            self.calls += 1
            if self.calls == 1:
                return _response(201, {"version": "1"})
            raise TimeoutError("synthetic poll timeout")

    client = FoundryDeploymentClient(
        PROJECT_ENDPOINT,
        lambda: "token",
        transport=CreateThenTimeoutTransport(),
    )

